/* Plan detail: stats, a 14-day download chart, the plan itself, and a download. */

const slug = decodeURIComponent(location.pathname.replace(/^\/plan\//, "").replace(/\/$/, ""));

const el = (tag, attrs = {}, ...kids) => {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (key === "class") node.className = value;
    else if (key === "html") node.innerHTML = value;
    else if (key.startsWith("on")) node.addEventListener(key.slice(2), value);
    else if (value !== null && value !== false) node.setAttribute(key, value);
  }
  for (const kid of kids.flat()) {
    if (kid == null) continue;
    node.append(kid.nodeType ? kid : document.createTextNode(kid));
  }
  return node;
};
const compact = (n) => n >= 1e6 ? (n / 1e6).toFixed(1) + "M"
  : n >= 1e3 ? (n / 1e3).toFixed(1) + "K" : String(n);

/* --- a very small markdown renderer -----------------------------------------
   The plan is generated by our own pipeline from our own template, so this only
   needs to cover what `render_plan` emits. Everything is escaped before any tag is
   introduced, so a documentation snippet containing HTML renders as text. */

const esc = (s) => s.replace(/[&<>"']/g,
  (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

/* Refs already linked in this document, so only the first gets the anchor id. */
let seenRefs = new Set();

function inline(text) {
  return esc(text)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    // Citations are the point of these plans: [^fastapi-1] becomes a superscript
    // link down to the Sources table rather than literal brackets in the prose.
    // Only the first mention carries the id — the same ref appears again in the
    // Sources table, and a duplicate id would make the back-link jump to the wrong
    // one (and is invalid HTML besides).
    .replace(/\[\^([^\]]+)\]/g, (_, ref) => {
      const first = !seenRefs.has(ref);
      seenRefs.add(ref);
      return `<sup><a href="#cite-${ref}"${first ? ` id="ref-${ref}"` : ""}>${ref}</a></sup>`;
    })
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[^*])\*([^*\n]+)\*/g, "$1<em>$2</em>")
    .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g,
      '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>')
    .replace(/&lt;(https?:\/\/[^\s&]+)&gt;/g,
      '<a href="$1" target="_blank" rel="noopener noreferrer">$1</a>');
}

function markdown(source) {
  seenRefs = new Set();
  const out = [];
  const lines = source.split("\n");
  let list = null;
  let table = null;

  const closeList = () => { if (list) { out.push(`</${list}>`); list = null; } };
  const closeTable = () => { if (table) { out.push("</tbody></table>"); table = null; } };

  for (let index = 0; index < lines.length; index++) {
    const line = lines[index];

    if (line.startsWith("```")) {
      closeList(); closeTable();
      const body = [];
      const language = line.slice(3).trim();
      while (++index < lines.length && !lines[index].startsWith("```")) body.push(lines[index]);
      out.push(`<pre><code class="lang-${esc(language)}">${esc(body.join("\n"))}</code></pre>`);
      continue;
    }

    const heading = /^(#{1,6})\s+(.*)$/.exec(line);
    if (heading) {
      closeList(); closeTable();
      out.push(`<h${heading[1].length}>${inline(heading[2])}</h${heading[1].length}>`);
      continue;
    }

    // A table is a header row, a separator row, then body rows.
    if (line.startsWith("|") && /^\|[\s:|-]+\|$/.test(lines[index + 1] || "")) {
      closeList();
      const cells = line.split("|").slice(1, -1).map((c) => `<th>${inline(c.trim())}</th>`);
      out.push(`<table><thead><tr>${cells.join("")}</tr></thead><tbody>`);
      table = true;
      index++;
      continue;
    }
    if (table && line.startsWith("|")) {
      const cells = line.split("|").slice(1, -1).map((c) => `<td>${inline(c.trim())}</td>`);
      out.push(`<tr>${cells.join("")}</tr>`);
      continue;
    }
    closeTable();

    const bullet = /^\s*[-*]\s+(.*)$/.exec(line);
    const numbered = /^\s*\d+\.\s+(.*)$/.exec(line);
    if (bullet || numbered) {
      const wanted = bullet ? "ul" : "ol";
      if (list !== wanted) { closeList(); out.push(`<${wanted}>`); list = wanted; }
      out.push(`<li>${inline((bullet || numbered)[1])}</li>`);
      continue;
    }
    closeList();

    if (line.startsWith("> ")) { out.push(`<blockquote>${inline(line.slice(2))}</blockquote>`); continue; }
    if (/^\s*---+\s*$/.test(line)) { out.push("<hr>"); continue; }
    const footnote = /^\[\^([^\]]+)\]:\s*(.*)$/.exec(line);
    if (footnote) {
      out.push(`<p class="footnote" id="cite-${esc(footnote[1])}">` +
        `<a href="#ref-${esc(footnote[1])}">${esc(footnote[1])}</a> ${inline(footnote[2])}</p>`);
      continue;
    }
    if (line.trim()) out.push(`<p>${inline(line)}</p>`);
  }
  closeList(); closeTable();
  return out.join("\n");
}

/* --- the download chart ------------------------------------------------------ */

function chart(values) {
  const width = 640, height = 110, pad = 16;
  const top = Math.max(...values, 1);
  const slot = (width - pad * 2) / values.length;
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("class", "chart");
  svg.setAttribute("viewBox", `0 0 ${width} ${height}`);
  svg.setAttribute("preserveAspectRatio", "none");

  values.forEach((value, index) => {
    const barHeight = Math.max((value / top) * (height - 34), value ? 2 : 1);
    const rect = document.createElementNS("http://www.w3.org/2000/svg", "rect");
    rect.setAttribute("x", (pad + index * slot + slot * 0.15).toFixed(1));
    rect.setAttribute("y", (height - 22 - barHeight).toFixed(1));
    rect.setAttribute("width", (slot * 0.7).toFixed(1));
    rect.setAttribute("height", barHeight.toFixed(1));
    // Zero days stay visible as a hairline so the axis reads as a timeline.
    if (!value) rect.setAttribute("class", "zero");
    const hint = document.createElementNS("http://www.w3.org/2000/svg", "title");
    hint.textContent = `${value} download${value === 1 ? "" : "s"}`;
    rect.append(hint);
    svg.append(rect);
  });

  const label = (text, x, anchor) => {
    const node = document.createElementNS("http://www.w3.org/2000/svg", "text");
    node.setAttribute("x", x); node.setAttribute("y", height - 6);
    node.setAttribute("text-anchor", anchor);
    node.textContent = text;
    svg.append(node);
  };
  label(`${values.length} days ago`, pad, "start");
  label("today", width - pad, "end");
  return svg;
}

/* --- page -------------------------------------------------------------------- */

async function load() {
  const page = document.getElementById("page");
  const response = await fetch(`/api/plans/${encodeURIComponent(slug)}`);
  if (!response.ok) {
    page.append(el("div", { class: "empty" }, response.status === 503
      ? "The catalogue is offline." : "No such plan."));
    return;
  }
  const plan = await response.json();
  document.title = `${plan.name} — ARK Scrapper`;

  const installs = el("div", {}, el("span", {}, "Installs"), compact(plan.installs));
  page.append(
    el("div", { class: "detail-head" },
      el("div", { class: "grow" },
        el("h1", {}, plan.name),
        el("div", { class: "req" }, plan.requirement),
        el("div", { class: "labels", style: "margin-top:10px" },
          plan.libraries.map((name) =>
            el("a", { class: "label", href: `/#catalogue` }, name)))),
      el("div", { class: "row" },
        el("button", { class: "primary", onclick: () => download(plan) }, "Download .md"),
        el("button", { onclick: () => copy(plan) }, "Copy"))),
    el("div", { class: "stat-strip" },
      installs,
      el("div", {}, el("span", {}, "Last 14d"), compact(plan.recent)),
      el("div", {}, el("span", {}, "Citations"), String(plan.citations)),
      el("div", {}, el("span", {}, "Phases"), String(plan.phases)),
      el("div", {}, el("span", {}, "Size"), `${Math.round(plan.bytes / 1024)} KB`),
      el("div", {}, el("span", {}, "Model"), plan.model || "—")),
    el("div", { class: "panel", style: "margin-top:24px" },
      el("h3", {}, "Downloads"),
      chart(plan.trend.length ? plan.trend : new Array(14).fill(0))),
    el("div", { class: "md", style: "margin-top:24px", html: markdown(plan.markdown || "") }));

  async function download() {
    // Going through the API endpoint is what counts the install; a blob built from
    // the markdown already in hand would not.
    const file = await fetch(`/api/plans/${encodeURIComponent(slug)}/download`);
    const blob = await file.blob();
    const url = URL.createObjectURL(blob);
    const link = el("a", { href: url, download: `${slug}-plan.md` });
    document.body.append(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
    installs.replaceChildren(el("span", {}, "Installs"),
      document.createTextNode(compact(Number(file.headers.get("X-Install-Count") || plan.installs + 1))));
  }

  async function copy() {
    await navigator.clipboard.writeText(plan.markdown || "");
    const note = el("div", { class: "toast" }, "Plan copied to clipboard");
    document.body.append(note);
    setTimeout(() => note.remove(), 2200);
  }
}

load();
